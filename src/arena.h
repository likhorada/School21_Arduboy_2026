#pragma once

#include "config.h"

namespace gc {

// Универсальный прямоугольник-хитбокс: используется для врагов и думми,
// а не для стен арены. Стены теперь попиксельные маски из assets/stage*.h.
struct Obstacle {
    uint8_t x;
    uint8_t y;
    uint8_t width;
    uint8_t height;
};

// Пиксель стены стейджа. Стейдж 1 (индекс 0) и любые вне диапазона пустые.
// x/y — внутри арены (0..ARENA_WIDTH-1 / 0..ARENA_HEIGHT-1).
bool stageWallPixel(uint8_t stage, uint8_t x, uint8_t y);

// Возвращаем координату в [0, extent); вход должен быть в [-extent, 2*extent).
int16_t wrapCoordinate(int16_t coordinate, int16_t extent);

// Проверяем весь прямоугольник игрока против попиксельной маски стен.
// x/y: левый верхний угол внутри арены, в единицах 1/16 пикселя. Края-тор, все
// пиксели бокса проверяются с учётом перехода через границу.
bool playerBlocked(uint8_t stage, int16_t x, int16_t y);

// Кратчайшее смещение с учётом краёв: от 126 до 2 при ширине 128 получается +4.
// На ровно половине ширины сохраняем знак (to - from); обе точки внутри арены.
int16_t shortestDelta(int16_t from, int16_t to, int16_t extent);

// Пересечение всего отрезка с прямоугольником, включая переходы через края.
// x/y и dx/dy в 1/16 пикселя, box в пикселях. Начальные позиции внутри арены.
// Смещение и размер прямоугольника по каждой оси не больше половины арены.
// Это проверка короткого пути, не луча на несколько оборотов вокруг поля.
bool segmentHitsBox(int16_t x, int16_t y, int16_t dx, int16_t dy,
                    const Obstacle& box);

// Проверяем отрезок против пиксельных стен стейджа (марш по доминантной оси с
// переносом через края). Прицеливание и пули используют одну геометрию.
bool shotBlocked(uint8_t stage, int16_t x, int16_t y, int16_t dx, int16_t dy);

} // пространство имён gc